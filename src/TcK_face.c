void draw_eye(uint8_t eye_side, const uint8_t eye_type[][20])
{ 
    uint8_t x_pos = (eye_side) ? 85 : 25;

    smoled_setpos(x_pos, 0);
    for(uint8_t byte = 0; byte < 20; byte++)
    {
        smoled_writebyte(pgm_read_byte(&(eye_type[0][byte])));
    }
 
    smoled_setpos(x_pos, 1);
    for(uint8_t byte = 0; byte < 20; byte++)
    {
        smoled_writebyte(pgm_read_byte(&(eye_type[1][byte])));
    }
}

void draw_mouth()
{
    smoled_setpos(23, 4);
    for(uint8_t byte = 0; byte < 80; byte++)
    {
        smoled_writebyte(pgm_read_byte(&(happy_mouth[0][byte])));
    }

    
    smoled_setpos(23, 5);
    for(uint8_t byte = 0; byte < 80; byte++)
    {
        smoled_writebyte(pgm_read_byte(&(happy_mouth[1][byte])));
    }

}
